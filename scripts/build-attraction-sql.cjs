// Generated catalogue insert; neither credentials nor existing votes are read/changed.
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const {attractions}=require('../assets/attraction-data.js');
const quote=value=>`'${value.replaceAll("'","''")}'`;
const seed='insert into public.travel_attractions (id,city_name,country,name,reference_url) values\n'+attractions.map(p=>`(${[p.id,p.city,p.country,p.name,p.referenceUrl].map(quote).join(',')})`).join(',\n')+'\non conflict (id) do update set city_name=excluded.city_name, country=excluded.country, name=excluded.name, reference_url=excluded.reference_url;';
const schema=fs.readFileSync(path.join(root,'supabase/attraction_ratings.schema.sql'),'utf8');
const sql='-- Generated by scripts/build-attraction-sql.cjs; run this entire file in SQL Editor.\n'+schema.replace('-- CATALOGUE_SEED',seed);
fs.writeFileSync(path.join(root,'supabase/attraction_ratings.sql'),sql);
fs.writeFileSync(path.join(root,'supabase/migrations/20260930000000_attraction_ratings.sql'),sql);
console.log(`Built attraction SQL: ${new Set(attractions.map(p=>p.city)).size} cities, ${attractions.length} sightseeing places.`);
