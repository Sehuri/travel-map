// Build the single-file Dashboard deployment artifact from the tested sources.
// No credentials are read or embedded.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const engine = fs.readFileSync(path.join(root, 'assets/discover-engine.js'), 'utf8');
const server = fs.readFileSync(path.join(root, 'supabase/functions/travel-discover/index.ts'), 'utf8');
const importLine = 'import "../../../assets/discover-engine.js";';
if (!server.includes(importLine)) throw new Error('Expected engine import was not found; review bundling before deployment.');
const output = '// Generated by scripts/build-discover-dashboard.cjs. Edit the source files, not this bundle.\n' + server.replace(importLine, engine);
fs.writeFileSync(path.join(root, 'supabase/travel-discover-dashboard.ts'), output);
console.log('Built supabase/travel-discover-dashboard.ts (no secrets).');
